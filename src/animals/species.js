export const MEDAL_NAMES = { aucune: 'Sans médaille', bronze: 'Bronze', argent: 'Argent', or: 'Or', diamant: 'Diamant', legendaire: 'Légendaire' };

export function medalFor(species, score, legendary = false) {
  const m = MEDALS[species];
  if (!m) return 'aucune';
  if (legendary) return 'legendaire';
  if (score >= m.diamant) return 'diamant';
  if (score >= m.or) return 'or';
  if (score >= m.argent) return 'argent';
  if (score >= m.bronze) return 'bronze';
  return 'aucune';
}
